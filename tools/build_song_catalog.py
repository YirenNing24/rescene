#!/usr/bin/env python3
"""Index local MP3 metadata and extract embedded covers without changing audio."""
import hashlib
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
AUDIO = ROOT / "assets/audio"
COVERS = ROOT / "assets/art/covers"
COVERS.mkdir(parents=True, exist_ok=True)
rows, seen, skipped = [], set(), []
soundtrack_release = re.compile(r"\bsoundtrack\b|^music from\b", re.IGNORECASE)
# Keep the original release, rather than additional language/tempo/recording versions.
alternate_version = re.compile(
    r"\b(?:japanese|english|sped[\s_-]*up|acoustic|instrumental|remix|special\s+video)\b",
    re.IGNORECASE,
)
for path in sorted(AUDIO.glob("*.mp3"), key=lambda item: ("(1)" in item.name, item.name.lower())):
    if path.name == "with.mp3":
        skipped.append(path.name + " (splash-only copy; tagged With is in the library)")
        continue
    if alternate_version.search(path.stem):
        skipped.append(path.name + " (alternate version; original release only)")
        continue
    metadata = json.loads(subprocess.check_output([
        "ffprobe", "-v", "error", "-show_entries",
        "format=duration:format_tags=title,artist,album:stream=codec_type",
        "-of", "json", str(path),
    ]))
    tags = {key.lower(): value for key, value in metadata["format"].get("tags", {}).items()}
    if soundtrack_release.search(tags.get("album", "")):
        skipped.append(path.name + " (soundtrack release)")
        continue
    fallback = re.sub(r"^RESCENE - ", "", path.stem)
    if path.name == "loveattack_acoustic.mp3":
        fallback = "LOVE ATTACK (Acoustic)"
    elif "Special Video" in path.stem:
        fallback = "Pretty Girl (Special Video)"
    elif "우리는 해" in path.stem:
        fallback = "우리는 해"
    title = tags.get("title", fallback)
    artist = tags.get("artist", "RESCENE")
    if alternate_version.search(title):
        skipped.append(path.name + " (alternate version in title metadata)")
        continue
    identity = (re.sub(r"\s+", " ", title).strip().casefold(), artist.strip().casefold())
    if identity in seen:
        skipped.append(path.name + " (duplicate title and artist)")
        continue
    seen.add(identity)
    cover = "res://assets/art/rescene-main-menu.png"
    if any(stream["codec_type"] == "video" for stream in metadata.get("streams", [])):
        temp = COVERS / "embedded-cover.jpg"
        subprocess.run([
            "ffmpeg", "-v", "error", "-y", "-i", str(path), "-map", "0:v:0",
            "-frames:v", "1", "-update", "1", str(temp),
        ], check=True)
        digest = hashlib.sha256(temp.read_bytes()).hexdigest()[:16]
        target = COVERS / (digest + ".jpg")
        if target.exists():
            temp.unlink()
        else:
            temp.rename(target)
        cover = "res://" + str(target.relative_to(ROOT))
    rows.append({
        "id": hashlib.sha256(path.name.encode()).hexdigest()[:12],
        "title": title, "artist": artist, "album": tags.get("album", "Special version"),
        "seconds": round(float(metadata["format"]["duration"])),
        "audio_path": "res://" + str(path.relative_to(ROOT)), "cover_path": cover,
        "playable_seconds": float(metadata["format"]["duration"]) * 0.5,
    })
rows.sort(key=lambda row: row["title"].casefold())
output = "class_name SongCatalog\n# Generated by tools/build_song_catalog.py. Audio loads only when selected.\nextends RefCounted\n\nconst SONGS: Array[Dictionary] = "
output += json.dumps(rows, ensure_ascii=False, indent=4) + "\n"
(ROOT / "scripts/song_catalog.gd").write_text(output)
print(f"Indexed {len(rows)} songs; {len(list(COVERS.glob('*.jpg')))} shared embedded covers.")
print("Skipped duplicate library entries (files retained):\n" + "\n".join(skipped))
