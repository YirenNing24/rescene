#!/usr/bin/env python3
"""Keep native and authoritative song-set memberships identical."""
import json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
source=(root/'scripts/song_catalog.gd').read_text()
songs=json.loads(source[source.index('= [')+2:source.rindex(']')+1])
pulse={'finest thing','with','inside out','meme','dragon'}
sets={}
records=[]
web_songs=[]
for song in songs:
    identifier='pulse' if song['title'].lower() in pulse else song['album'].lower().replace(' ','_')
    entry=sets.setdefault(identifier,{'id':identifier,'name':song['album'],'song_ids':[],'songs':[]})
    entry['song_ids'].append(song['id']);entry['songs'].append(song['title'])
    records.append({'id':song['id'],'title':song['title'],'album':song['album'],'set_id':identifier})
    web_songs.append({'id':song['id'],'title':song['title'],'artist':song['artist'],'album':song['album'],'seconds':song['seconds'],'cover':'/images/'+Path(song['cover_path']).stem+'.webp','set_id':identifier,'duration':song['playable_seconds']})
assert {s.lower() for s in sets['pulse']['songs']}==pulse
pulse_order={name:i for i,name in enumerate(["Finest Thing","With","Inside Out","MEME","Dragon"])}
pairs=sorted(zip(sets["pulse"]["songs"],sets["pulse"]["song_ids"]),key=lambda pair:pulse_order[pair[0]])
sets["pulse"]["songs"]=[pair[0] for pair in pairs];sets["pulse"]["song_ids"]=[pair[1] for pair in pairs]
ordered=[sets.pop('pulse'),*sorted(sets.values(),key=lambda x:x['name'].lower())]
(root/'backend/song_sets.json').write_text(json.dumps(records,indent=2)+'\n')
(root/'webapp/src/songs.json').write_text(json.dumps(web_songs,indent=2,ensure_ascii=False)+'\n')
(root/'scripts/song_sets.gd').write_text('class_name SongSets\nextends RefCounted\n## Generated by tools/build_card_sets.py. Shared with backend/song_sets.json.\nconst MEMBERS: Array[String] = ["Woni", "Liv", "Minami", "May", "Zena"]\nconst SETS: Array[Dictionary] = '+json.dumps(ordered,indent=4)+'''\n
static func for_song(song_id: String) -> String:
\tfor entry: Dictionary in SETS:
\t\tif StrictData.array(entry.song_ids).has(song_id): return str(entry.id)
\treturn ""

static func find_set(set_id: String) -> Dictionary:
\tfor entry: Dictionary in SETS:
\t\tif str(entry.id) == set_id: return entry
\treturn {}
''')
print(f'{len(songs)} songs / {len(ordered)} sets; PULSE membership verified')
