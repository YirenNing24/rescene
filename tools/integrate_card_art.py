#!/usr/bin/env python3
"""Import approved card composites without changing their borders or portrait crops."""
import hashlib
import json
import shutil
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
MEMBERS = ['Woni', 'Liv', 'Minami', 'May', 'Zena']
RELEASES = [
    ('pulse', 'PULSE', 'pulse', 'pulse-le-set-tight-corners', '{member}-pulse-le-v5.png'),
    ('re:scene', 'Re:Scene', 're-scene', 'four-album-le-sets-v2/re-scene', '{member}-re-scene-le-v2.png'),
    ('scenedrome', 'SCENEDROME', 'scenedrome', 'scenedrome/member-set/uniform-v2', '{member}-scenedrome-le-v2.png'),
    ('glow_up', 'Glow Up', 'glow-up', 'four-album-le-sets-v2/glow-up', '{member}-glow-up-le-v2.png'),
    ('dearest', 'Dearest', 'dearest', 'four-album-le-sets-v2/dearest', '{member}-dearest-le-v2.png'),
    ('lip_bomb', 'lip bomb', 'lip-bomb', 'four-album-le-sets-v2/lip-bomb', '{member}-lip-bomb-le-v2.png'),
    ('pretty_girl_-_special_single', 'Pretty Girl', 'pretty-girl', 'singles-le-member-sets/pretty-girl', '{member}-pretty-girl-le-v1.png'),
    ('runaway', 'Runaway', 'runaway', 'singles-le-member-sets/runaway', '{member}-runaway-le-v1.png'),
    ('[rescene_x_???]', 'Busy Boy', 'busy-boy', 'singles-le-member-sets/busy-boy', '{member}-busy-boy-le-v1.png'),
]

def main():
    releases, sources = [], []
    for number, (set_id, name, slug, directory, pattern) in enumerate(RELEASES, 1):
        releases.append(dict(number=number, set_id=set_id, name=name, slug=slug))
        for member in MEMBERS:
            source = ROOT / 'output/cards' / directory / pattern.format(member=member.lower())
            assert source.is_file(), source
            image = Image.open(source).convert('RGBA')
            assert image.size == (1008, 1560), (source, image.size)
            image.thumbnail((662, 1024), Image.Resampling.LANCZOS)
            targets = [ROOT/'assets/art/cards/releases'/slug/(member.lower()+'.webp'),
                       ROOT/'webapp/public/images/cards/v1'/slug/(member.lower()+'.webp')]
            for target in targets: target.parent.mkdir(parents=True, exist_ok=True)
            image.save(targets[0], 'WEBP', quality=92, method=6, exact=True)
            shutil.copyfile(targets[0], targets[1])
            sources.append(dict(set_id=set_id, member=member, source=str(source.relative_to(ROOT)),
                                source_sha256=hashlib.sha256(source.read_bytes()).hexdigest(),
                                runtime_sha256=hashlib.sha256(targets[0].read_bytes()).hexdigest(),
                                dimensions=list(image.size)))
    payload = json.dumps(releases, indent=2, ensure_ascii=False)+'\n'
    (ROOT/'backend/card_releases.json').write_text(payload)
    (ROOT/'webapp/src/card-releases.json').write_text(payload)
    (ROOT/'assets/art/cards/releases/provenance.json').write_text(json.dumps(sources, indent=2)+'\n')
    gd = 'class_name CardReleases\nextends RefCounted\n## Generated by tools/integrate_card_art.py; numeric identities are permanent.\n'
    gd += 'const RELEASES: Array[Dictionary] = '+payload+'\n'
    gd += '''static func find_set(set_id: String) -> Dictionary:
	for release: Dictionary in RELEASES:
		if str(release.set_id) == set_id: return release
	return {}

static func template_id(release: Dictionary, member: int) -> String:
	return "scene_%02d" % (member+1) if StrictData.integer(release.number) == 1 else "le_%s_%02d" % [str(release.slug).replace("-", "_"), member+1]

static func templates() -> Array[Dictionary]:
	var cards: Array[Dictionary] = []
	var accents: Array[String] = ["c7bbff", "e0b3cf", "a9cbea", "c8b2e6", "b1d6d4"]
	for release: Dictionary in RELEASES:
		for member: int in 5:
			cards.append({"id":template_id(release, member), "category":"cards", "name":SongSets.MEMBERS[member]+" · "+str(release.name), "member_name":SongSets.MEMBERS[member], "member":member, "set_id":str(release.set_id), "series":str(release.name), "art_slug":str(release.slug), "tag":"LE · PHOTO CARD", "price":450, "accent":accents[member], "description":"An individual %s LE card. Rolls 7–10%% Perfect Score, 7–10 Recovery and one permanent skill. Refine to level 100; sacrifice eligible cards to strengthen its skill." % str(release.name), "contents":"1 unique LE card / Level 1 / 1 star", "detail":"Each stat value: 25% chance. One of six skills, equally likely. Rolls are permanent. Initial sale: 50 per member per set; future admin mints and artwork reissues are allowed."})
	return cards

static func artwork(item: Dictionary) -> String:
	var release: Dictionary = find_set(str(item.get("set_id", "pulse")))
	if release.is_empty(): return ""
	var member: String = str(item.get("member_name", item.get("member", ""))).to_lower()
	if member not in ["woni", "liv", "minami", "may", "zena"]: return ""
	return "res://assets/art/cards/releases/%s/%s.webp" % [str(release.slug), member]
'''
    (ROOT/'scripts/card_releases.gd').write_text(gd)
    print('Imported 45 approved cards across 9 releases; shared native/web identities generated.')

if __name__ == '__main__':
    main()
